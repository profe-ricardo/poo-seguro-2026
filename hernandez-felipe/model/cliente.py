from config.app_config import app_config, conectar_db

class Cliente():
    def __init__(self, nombre: str, telefono: str, correo: str):
        self.nombre = nombre
        self.telefono = telefono
        self.correo = correo

    consulta_sql= """
        create table if not exists clientes(
            id NUMBER generated by default as identity (start with 1 increment by 1) primary key,
            nombre varchar2(100),
            telefono varchar2(30),
            correo varchar2(100)
        );
    """
    try:
        conn = conectar_db()

        if conn:
            cursor = conn.cursor()
            cursor.execute(consulta_sql)
            print("[INFO] Tabla 'clientes' creada ")
    except Exception as e:
        print(f"[ERROR] No se pudo crear la tabla 'clientes': {e}")

    


    except Exception as e:
        print(f"[ERROR] No se pudo conectar a la base de datos: {e}")


    def mostrar_datos(self):
        return f"Nombre: {self.nombre} | Telefono: {self.telefono} | Correo: {self.correo}"